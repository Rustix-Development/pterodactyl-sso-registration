/** Lucide names for the generic OpenID Connect icons. */
const GENERIC: Record<string, string> = {
    key: 'key-round',
    shield: 'shield-check',
    cloud: 'cloud',
    lock: 'lock',
    building: 'building-2',
    globe: 'globe',
};

/**
 * A provider's logo, or the generic icon chosen for an OpenID Connect provider.
 *
 * @param {{ icon: string }} props
 * @returns {JSX.Element}
 */
export default function ProviderIcon({ icon }: { icon: string }) {
    const brand = BRANDS[icon];
    if (brand) return brand();

    return <NamedIcon name={GENERIC[icon] ?? 'log-in'} className={'rxrg:size-5 rxrg:shrink-0'} aria-hidden />;
}
